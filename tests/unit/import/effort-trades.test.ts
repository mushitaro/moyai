// 作業日報の人数の欄：職種の語と略の 1 字（11-07、運営者の試験の資料で読めなかった書き方。どの施設の日報にもある職種の語）
import { describe, expect, it } from "vitest";
import { parsePersons } from "../../../src/import/text";

describe("人数の欄の職種の語と略", () => {
  it.each([
    ["築炉工3 作業員2", 5],
    ["計装工2 技術員1", 3],
    ["機械工1 検査員2", 3],
    ["作業員1 保温工2 塗装工2", 5],
    ["機1・検2", 3],
    ["電2・配1", 3],
    ["作2・保1・塗1", 4],
    ["築2・作4", 6],
    ["計2・技1", 3],
    ["計4名（機械工3）", 4],
  ])("%s は %i 人", (s, n) => {
    expect(parsePersons(s)?.n).toBe(n);
  });
  it("職種の語に無い語は読まない", () => {
    expect(parsePersons("職員2 業者3")).toBeNull();
  });
});
